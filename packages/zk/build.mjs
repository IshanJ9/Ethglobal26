// Builds the Groth16 score-threshold circuit and copies the artifacts where they are used.
//   pnpm --filter @proofwork/zk build
// Trusted setup: a small powers-of-tau (2^12) plus one phase-2 contribution, run locally. That is a
// single-party setup, fine for a hackathon and stated as such in the README; production needs a ceremony.
import { execSync } from "node:child_process";
import { copyFileSync, existsSync, mkdirSync, readFileSync, renameSync, rmSync, writeFileSync } from "node:fs";
import { randomBytes } from "node:crypto";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "../..");
const b = join(here, "build");
mkdirSync(b, { recursive: true });
const sh = (cmd) => {
  console.log(`$ ${cmd}`);
  execSync(cmd, { cwd: here, stdio: ["ignore", "inherit", "inherit"], shell: true });
};
const bin = (x) => join(here, "node_modules", ".bin", process.platform === "win32" ? `${x}.CMD` : x);
const q = (p) => `"${p}"`;

// circom2 runs as WASI and cannot write nested Windows paths: compile a flat copy in the package root, then move.
writeFileSync(join(here, "score_threshold.circom"), readFileSync(join(here, "circuits/score_threshold.circom"), "utf8").replaceAll('"../node_modules/', '"node_modules/'));
sh(`${q(bin("circom2"))} score_threshold.circom --r1cs --wasm --sym`);
for (const f of ["score_threshold.r1cs", "score_threshold.sym"]) renameSync(join(here, f), join(b, f));
rmSync(join(b, "score_threshold_js"), { recursive: true, force: true });
renameSync(join(here, "score_threshold_js"), join(b, "score_threshold_js"));
rmSync(join(here, "score_threshold.circom"));
const ptau = join(b, "pot12_final.ptau");
if (!existsSync(ptau)) {
  sh(`${q(bin("snarkjs"))} powersoftau new bn128 12 build/pot12_0000.ptau`);
  sh(`${q(bin("snarkjs"))} powersoftau contribute build/pot12_0000.ptau build/pot12_0001.ptau --name="proofwork" -e="${randomBytes(32).toString("hex")}"`);
  sh(`${q(bin("snarkjs"))} powersoftau prepare phase2 build/pot12_0001.ptau build/pot12_final.ptau`);
}
sh(`${q(bin("snarkjs"))} groth16 setup build/score_threshold.r1cs build/pot12_final.ptau build/score_0000.zkey`);
sh(`${q(bin("snarkjs"))} zkey contribute build/score_0000.zkey build/score_final.zkey --name="proofwork-phase2" -e="${randomBytes(32).toString("hex")}"`);
sh(`${q(bin("snarkjs"))} zkey export verificationkey build/score_final.zkey build/vkey.json`);
sh(`${q(bin("snarkjs"))} zkey export solidityverifier build/score_final.zkey build/Groth16Verifier.sol`);

// copy artifacts
const web = join(root, "apps/web/public/zk");
mkdirSync(web, { recursive: true });
copyFileSync(join(b, "score_threshold_js", "score_threshold.wasm"), join(web, "score_threshold.wasm"));
copyFileSync(join(b, "score_final.zkey"), join(web, "score_threshold.zkey"));
copyFileSync(join(b, "vkey.json"), join(web, "vkey.json"));
copyFileSync(join(b, "vkey.json"), join(here, "vkey.json"));
const sol = readFileSync(join(b, "Groth16Verifier.sol"), "utf8").replace("contract Groth16Verifier", "contract ScoreThresholdVerifier");
writeFileSync(join(root, "contracts/src/ScoreThresholdVerifier.sol"), `// GENERATED by packages/zk/build.mjs (snarkjs groth16). Do not edit.\n${sol}`);
console.log("\nZK build done: apps/web/public/zk/{score_threshold.wasm,score_threshold.zkey,vkey.json}, contracts/src/ScoreThresholdVerifier.sol");
